import AppKit
import Foundation
import OSLog

@MainActor
protocol ClipboardItemReading {
    var types: [String] { get }
    func data(forType type: String) -> Data?
    func string(forType type: String) -> String?
}

@MainActor
protocol ClipboardReading: AnyObject {
    var changeCount: Int { get }
    var accessDenied: Bool { get }
    var types: [String] { get }
    var items: [any ClipboardItemReading]? { get }
    func string(forType type: String) -> String?
}

@MainActor
private final class SystemClipboardItem: ClipboardItemReading {
    private let item: NSPasteboardItem

    init(_ item: NSPasteboardItem) { self.item = item }

    var types: [String] { item.types.map(\.rawValue) }

    func data(forType type: String) -> Data? {
        item.data(forType: NSPasteboard.PasteboardType(rawValue: type))
    }

    func string(forType type: String) -> String? {
        item.string(forType: NSPasteboard.PasteboardType(rawValue: type))
    }
}

@MainActor
private final class SystemClipboardReader: ClipboardReading {
    private let pasteboard: NSPasteboard

    init(_ pasteboard: NSPasteboard) { self.pasteboard = pasteboard }

    var changeCount: Int { pasteboard.changeCount }
    var types: [String] { (pasteboard.types ?? []).map(\.rawValue) }
    var items: [any ClipboardItemReading]? { pasteboard.pasteboardItems?.map(SystemClipboardItem.init) }

    var accessDenied: Bool {
        if #available(macOS 15.4, *) { pasteboard.accessBehavior == .alwaysDeny }
        else { false }
    }

    func string(forType type: String) -> String? {
        pasteboard.string(forType: NSPasteboard.PasteboardType(rawValue: type))
    }
}

@MainActor
final class ScheduledCaptureRetry {
    private let cancelAction: () -> Void
    private(set) var isCancelled = false

    init(cancel: @escaping () -> Void = {}) { cancelAction = cancel }

    func cancel() {
        guard !isCancelled else { return }
        isCancelled = true
        cancelAction()
    }
}

@MainActor
final class ClipboardRecorder: NSObject {
    typealias RetryScheduler = @MainActor (TimeInterval, @escaping @MainActor () -> Void) -> ScheduledCaptureRetry
    typealias SnapshotSaver = @MainActor (ClipboardSnapshot, @escaping @MainActor @Sendable (SnapshotCommitResult) -> Void) -> Void

    private enum RecordingState {
        case notStarted
        case recording
        case paused
        case suspended
        case stopped
    }

    private struct ActiveRead {
        let id: UUID
        let epoch: UUID
        var retriesRemaining: Int
    }

    private struct InFlightCommit {
        let id: UUID
        let epoch: UUID
        let changeCount: Int
    }

    private let logger = Logger(subsystem: "local.charslee.localclips", category: "capture")
    private let store: HistoryStore
    private let clipboard: any ClipboardReading
    private let preferences: UserDefaults
    private let scheduleRetry: RetryScheduler
    private let saveSnapshot: SnapshotSaver
    private var timer: Timer?
    private var lastHandledChangeCount: Int?
    private var captureEpoch = UUID()
    private var activeRead: ActiveRead?
    private var pendingRetry: ScheduledCaptureRetry?
    private var inFlightCommit: InFlightCommit?
    private var recordingState: RecordingState
    private var captureOutcome: CaptureStatus = .waiting
    private var ownWrite: (changeCount: Int, digest: String)?

    var onStatusChange: ((CaptureStatus) -> Void)?
    private(set) var status: CaptureStatus = .waiting

    var hasStartedRecording: Bool { preferences.bool(forKey: "recordingStarted") }
    var isPaused: Bool {
        if case .paused = recordingState { return true }
        return false
    }
    var isRecording: Bool {
        if case .recording = recordingState { return true }
        return false
    }
    var isSaving: Bool { inFlightCommit != nil }
    var hasPendingRetry: Bool { pendingRetry != nil }
    var lastHandledCount: Int? { lastHandledChangeCount }

    private let supportedTypes: Set<String> = [
        NSPasteboard.PasteboardType.string.rawValue,
        "public.rtf", "com.apple.rtfd", "public.html", "public.png", "public.tiff", "public.jpeg", "public.heic", "public.heif", "public.gif",
        "public.url", "public.file-url",
    ]
    private let filteredTypes = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
    ]

    init(
        store: HistoryStore,
        clipboardReader: (any ClipboardReading)? = nil,
        preferences: UserDefaults = .standard,
        retryScheduler: RetryScheduler? = nil,
        snapshotSaver: SnapshotSaver? = nil
    ) {
        self.store = store
        clipboard = clipboardReader ?? SystemClipboardReader(.general)
        self.preferences = preferences
        scheduleRetry = retryScheduler ?? { delay, operation in
            let work = DispatchWorkItem { operation() }
            DispatchQueue.main.asyncAfter(deadline: .now() + delay, execute: work)
            return ScheduledCaptureRetry { work.cancel() }
        }
        saveSnapshot = snapshotSaver ?? { snapshot, completion in store.save(snapshot, completion: completion) }
        if preferences.bool(forKey: "recordingStarted") {
            recordingState = preferences.bool(forKey: "recordingPaused") ? .paused : .recording
        } else {
            recordingState = .notStarted
        }
        super.init()
        NSWorkspace.shared.notificationCenter.addObserver(self, selector: #selector(willSleep), name: NSWorkspace.willSleepNotification, object: nil)
        NSWorkspace.shared.notificationCenter.addObserver(self, selector: #selector(wake), name: NSWorkspace.didWakeNotification, object: nil)
        updateStatus()
    }

    func start() {
        guard hasStartedRecording, isRecording, timer == nil else { return }
        if lastHandledChangeCount == nil { establishNewEpoch(baseline: clipboard.changeCount) }
        let timer = Timer(timeInterval: 0.3, target: self, selector: #selector(tick), userInfo: nil, repeats: true)
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
        setOutcome(.recording)
    }

    func pause() {
        guard hasStartedRecording, !isPaused else { return }
        recordingState = .paused
        preferences.set(true, forKey: "recordingPaused")
        invalidateCaptureWork()
        timer?.invalidate()
        timer = nil
        updateStatus()
    }

    func stop() {
        if case .stopped = recordingState { return }
        recordingState = .stopped
        invalidateCaptureWork()
        timer?.invalidate()
        timer = nil
        updateStatus()
    }

    func resume() {
        if case .stopped = recordingState { return }
        preferences.set(true, forKey: "recordingStarted")
        preferences.set(false, forKey: "recordingPaused")
        recordingState = .recording
        establishNewEpoch(baseline: clipboard.changeCount)
        start()
        setOutcome(.recording)
    }

    func noteOwnWrite(_ snapshot: ClipboardSnapshot, changeCount: Int) {
        ownWrite = (changeCount, snapshot.digest)
        establishNewEpoch(baseline: changeCount)
    }

    @objc private func wake() {
        guard case .suspended = recordingState else { return }
        recordingState = .recording
        invalidateCaptureWork()
        start()
        tick()
    }

    @objc private func willSleep() {
        guard isRecording else { return }
        recordingState = .suspended
        invalidateCaptureWork()
        timer?.invalidate()
        timer = nil
        updateStatus()
    }

    @objc private func tick() {
        guard isRecording, inFlightCommit == nil, store.isReady, activeRead == nil else { return }
        let currentCount = clipboard.changeCount
        guard lastHandledChangeCount != currentCount else { return }
        activeRead = ActiveRead(id: UUID(), epoch: captureEpoch, retriesRemaining: 2)
        attemptRead(expectedCount: currentCount)
    }

    func pollNow() { tick() }

    private func attemptRead(expectedCount: Int) {
        guard isRecording, inFlightCommit == nil,
              var read = activeRead, read.epoch == captureEpoch else { return }

        if clipboard.accessDenied {
            finishRead(read, changeCount: clipboard.changeCount, outcome: .unavailable("剪贴板读取权限已拒绝"))
            return
        }

        let before = clipboard.changeCount
        guard before == expectedCount else {
            retryOrFinish(read, at: before)
            return
        }
        let allTypes = Set(clipboard.types)
        if let marker = filteredTypes.first(where: allTypes.contains) {
            finishRead(read, changeCount: before, outcome: .filtered(Self.reason(for: marker)))
            return
        }

        let attribution = sourceAttribution()
        if let bundleID = attribution.bundleID,
           (preferences.stringArray(forKey: "ignoredBundleIDs") ?? []).contains(bundleID) {
            finishRead(read, changeCount: before, outcome: .filtered("来源应用已排除"))
            return
        }

        let pasteboardItems = clipboard.items ?? []
        guard !pasteboardItems.isEmpty, pasteboardItems.count <= 100 else {
            finishRead(read, changeCount: before, outcome: pasteboardItems.isEmpty ? .noSupportedContent : .tooLarge)
            return
        }
        var items: [CapturedItem] = []
        var totalBytes = 0
        for (itemPosition, pasteboardItem) in pasteboardItems.enumerated() {
            let types = pasteboardItem.types
            var representations: [CapturedRepresentation] = []
            for (position, type) in types.enumerated() where supportedTypes.contains(type) {
                var data = pasteboardItem.data(forType: type)
                if data == nil, type == NSPasteboard.PasteboardType.string.rawValue,
                   let string = pasteboardItem.string(forType: type) {
                    data = Data(string.utf8)
                }
                if data == nil, type == "public.url" || type == "public.file-url",
                   let string = pasteboardItem.string(forType: type) {
                    data = Data(string.utf8)
                }
                guard let data else { continue }
                guard data.count <= 32 * 1024 * 1024 else {
                    finishRead(read, changeCount: before, outcome: .tooLarge)
                    return
                }
                totalBytes += data.count
                guard totalBytes <= 64 * 1024 * 1024 else {
                    finishRead(read, changeCount: before, outcome: .tooLarge)
                    return
                }
                let bookmarkData: Data?
                if type == "public.file-url", let url = Self.fileURL(from: data) {
                    bookmarkData = try? url.bookmarkData(options: [], includingResourceValuesForKeys: nil, relativeTo: nil)
                } else {
                    bookmarkData = nil
                }
                representations.append(CapturedRepresentation(typeIdentifier: type, position: position, data: data, bookmarkData: bookmarkData))
            }
            guard !representations.isEmpty else {
                finishRead(read, changeCount: before, outcome: .noSupportedContent)
                return
            }
            items.append(CapturedItem(position: itemPosition, representations: representations))
        }
        guard !items.isEmpty else {
            finishRead(read, changeCount: before, outcome: .noSupportedContent)
            return
        }
        guard clipboard.changeCount == before else {
            retryOrFinish(read, at: clipboard.changeCount)
            return
        }

        let snapshot = ClipboardSnapshot(
            items: items,
            sourceBundleID: attribution.bundleID,
            sourceName: attribution.name,
            sourceConfidence: attribution.confidence
        )
        guard clipboard.changeCount == before else {
            retryOrFinish(read, at: clipboard.changeCount)
            return
        }
        if let ownWrite, ownWrite.changeCount == before, ownWrite.digest == snapshot.digest {
            self.ownWrite = nil
            finishRead(read, changeCount: before, outcome: .waiting)
            return
        }

        activeRead = nil
        pendingRetry?.cancel()
        pendingRetry = nil
        let commit = InFlightCommit(id: UUID(), epoch: read.epoch, changeCount: before)
        inFlightCommit = commit
        read.retriesRemaining = 0
        saveSnapshot(snapshot) { [weak self] result in
            self?.finishCommit(id: commit.id, result: result)
        }
    }

    private func retryOrFinish(_ read: ActiveRead, at currentCount: Int) {
        guard var active = activeRead, active.id == read.id, active.epoch == captureEpoch else { return }
        if active.retriesRemaining > 0 {
            active.retriesRemaining -= 1
            activeRead = active
            let readID = active.id
            let epoch = active.epoch
            pendingRetry = scheduleRetry(0.05) { [weak self] in
                guard let self,
                      self.captureEpoch == epoch,
                      self.isRecording,
                      let pending = self.activeRead,
                      pending.id == readID,
                      pending.epoch == epoch else { return }
                self.pendingRetry = nil
                self.attemptRead(expectedCount: currentCount)
            }
        } else {
            activeRead = nil
            pendingRetry = nil
            setOutcome(.unstableClipboard)
        }
    }

    private func finishRead(_ read: ActiveRead, changeCount: Int, outcome: CaptureStatus) {
        guard activeRead?.id == read.id, read.epoch == captureEpoch else { return }
        activeRead = nil
        pendingRetry?.cancel()
        pendingRetry = nil
        lastHandledChangeCount = changeCount
        setOutcome(outcome)
    }

    private func finishCommit(id: UUID, result: SnapshotCommitResult) {
        guard let commit = inFlightCommit, commit.id == id else { return }
        inFlightCommit = nil
        guard commit.epoch == captureEpoch, isRecording else { return }
        lastHandledChangeCount = commit.changeCount
        switch result {
        case .saved: setOutcome(.saved)
        case .budgetFull: setOutcome(.budgetFull)
        case .lowSpace: setOutcome(.lowSpace)
        case .failed: setOutcome(.writeFailed)
        }
    }

    private func establishNewEpoch(baseline: Int?) {
        invalidateCaptureWork()
        lastHandledChangeCount = baseline
        ownWrite = ownWrite.flatMap { $0.changeCount == baseline ? $0 : nil }
    }

    private func invalidateCaptureWork() {
        captureEpoch = UUID()
        activeRead = nil
        pendingRetry?.cancel()
        pendingRetry = nil
    }

    private func sourceAttribution() -> (bundleID: String?, name: String?, confidence: String) {
        let declared = clipboard.string(forType: "org.nspasteboard.source")
        if let value = declared, !value.isEmpty {
            let app = NSWorkspace.shared.runningApplications.first { $0.bundleIdentifier == value }
            return (value, app?.localizedName, "declared")
        }
        if let app = NSWorkspace.shared.frontmostApplication, app.bundleIdentifier != Bundle.main.bundleIdentifier {
            return (app.bundleIdentifier, app.localizedName, "foregroundHeuristic")
        }
        return (nil, nil, "unknown")
    }

    private static func fileURL(from data: Data) -> URL? {
        let url = URL(dataRepresentation: data, relativeTo: nil)
            ?? String(data: data, encoding: .utf8).flatMap(URL.init(string:))
        return url?.isFileURL == true ? url : nil
    }

    private func setOutcome(_ outcome: CaptureStatus) {
        captureOutcome = outcome
        updateStatus()
        if case .writeFailed = outcome { logger.error("snapshot write failed") }
    }

    private func updateStatus() {
        let value: CaptureStatus
        switch recordingState {
        case .notStarted, .stopped, .suspended: value = .waiting
        case .paused: value = .paused
        case .recording: value = captureOutcome
        }
        guard value != status else { return }
        status = value
        onStatusChange?(value)
    }

    var readPermissionLabel: String {
        guard #available(macOS 15.4, *) else { return "系统读取状态未知" }
        let pasteboard = NSPasteboard.general
        return switch pasteboard.accessBehavior {
        case .default: "首次访问待系统决定"
        case .ask: "系统访问策略：每次确认"
        case .alwaysAllow: "系统读取已允许"
        case .alwaysDeny: "系统读取已拒绝"
        @unknown default: "系统读取状态未知"
        }
    }

    private static func reason(for marker: String) -> String {
        switch marker {
        case "org.nspasteboard.ConcealedType": "保密标记"
        case "org.nspasteboard.TransientType": "临时内容标记"
        default: "自动生成内容标记"
        }
    }
}
